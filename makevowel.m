function [B,A] = makevowel(a,f,fs)

% Овде је направљена каскадна реализација. Сваки ред у матрици Ai 
% представља један пар конјуговано-комплексних полова, односно један формант.

% Математички трик: множењем Ai(1)*Ai(2)*Ai(3)*Ai(4) 
% заправо се врши конволуција коефицијената полинома у позадини. 
% Тиме се спајају 4 мала филтра другог реда у један велики филтар 8. реда.

fz = 2*pi*f/fs;
z = tf('z',1/fs);
Ai = [ones(4,1) -2*cos(fz).*a a.^2]*[1;z^-1;z^-2];
Az = Ai(1)*Ai(2)*Ai(3)*Ai(4);

% Преносна функција: 1/Az значи да се прави all-pole модел. 
% То је суштина АР модела о којој смо причали – нема нула,
% већ само резонанције.
[B, A] = tfdata(1/Az,'v'); % враћа редом векторе

end