function [a,s] = estimate_LPC(rxx,p)
% estimate_LPC рачуна LPC коефицијенте из Yule-Walker-ових једначина
% rxx садржи аутокорелацију за кашњења од -p до p
% a је вектор коефицијената полинома A(z) = 1 + a1 z^-1 + ... + ap z^-p
% s је процена снаге грешке предикције

% формирамо Toeplitz-ову матрицу Yule-Walker система
R = toeplitz(rxx(p+1:2*p),rxx(p+1:-1:2));

% решавамо систем R*a = -r без експлицитног рачунања инверза
coef = -R\rxx(p+2:end);

% процена варијансе грешке предикције
s = rxx(p+1) + sum(coef.*rxx(p:-1:1));
s = real(s);
s = max(s,eps);

% додајемо први коефицијент који је увек једнак 1
a = [1; coef].';
end
